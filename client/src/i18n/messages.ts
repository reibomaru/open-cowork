// Build dotted-key union from the message tree (e.g. "chat.welcomeTitle")
type DotKey<T, P extends string = ""> = {
  [K in keyof T & string]: T[K] extends string
    ? `${P}${K}`
    : T[K] extends object
      ? DotKey<T[K], `${P}${K}.`>
      : never
}[keyof T & string]

export type TKey = DotKey<Messages>
